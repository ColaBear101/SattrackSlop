/*
 * Bake earth/transmitters.js from SatNOGS DB.
 *
 * Doppler needs a frequency, and the honest way to get one is not to invent it.
 * SatNOGS DB publishes the transmitter records the amateur satellite community
 * maintains - downlink, mode, baud, service, and whether the thing is still
 * alive - anonymously and in one request. The same database already supplies
 * most of the embedded catalogue, so this adds a field to a source the page is
 * already trusting rather than a new dependency.
 *
 * One request, not 2158. The whole table is ~3.9 MB and comes back unpaginated
 * in about six seconds; asking per object would be 2158 requests against
 * someone else's server for the same bytes.
 *
 * What is kept, and why:
 *   - status 'active' only. Dead transmitters on live satellites are the norm,
 *     and tuning to one is worse than having no number at all.
 *   - a downlink frequency must be present. An uplink-only record cannot be
 *     listened to, which is what this is for.
 *   - deduplicated on (frequency, mode): the same transmitter is often filed
 *     several times with different descriptions.
 *   - at most MAX_TX per object, lowest frequency first, so the file stays a
 *     reference rather than an archive.
 *   - only objects that are actually in the embedded catalogue. The rest cannot
 *     be selected on the page, so carrying them is dead weight.
 *
 *   node verification/fetch-transmitters.js
 */
const fs = require('fs');
const path = require('path');

const API = 'https://db.satnogs.org/api/transmitters/?format=json';
const CATALOG = path.join(__dirname, 'catalog.txt');
const OUT = path.join(__dirname, '..', 'earth', 'transmitters.js');
const MAX_TX = 4;
const DESC_MAX = 44;

function catalogueIds() {
  const lines = fs.readFileSync(CATALOG, 'utf8').split(/\r?\n/);
  const ids = new Set();
  for (const l of lines)
    if (l.startsWith('1 ') && l.length > 7) ids.add(parseInt(l.substring(2, 7), 10));
  return ids;
}

(async () => {
  const ids = catalogueIds();
  console.log('embedded catalogue: ' + ids.size + ' objects');

  const t0 = Date.now();
  const res = await fetch(API, { headers: { 'User-Agent': 'sattrack-ground-track-build' } });
  if (!res.ok) { console.error('SatNOGS returned HTTP ' + res.status); process.exit(1); }
  const all = await res.json();
  console.log('SatNOGS DB        : ' + all.length + ' transmitter records in '
              + ((Date.now() - t0) / 1000).toFixed(1) + ' s');

  const tx = {};
  let kept = 0, skippedDead = 0, skippedNoDown = 0, skippedNotOurs = 0;

  for (const r of all) {
    const id = r.norad_cat_id;
    if (!id || !ids.has(id)) { skippedNotOurs++; continue; }
    if (r.status !== 'active') { skippedDead++; continue; }
    const hz = r.downlink_low;
    if (!hz || !isFinite(hz)) { skippedNoDown++; continue; }

    const mode = (r.uplink_mode && r.type === 'Transmitter' ? null : r.mode) || r.mode || '';
    let desc = (r.description || '').replace(/\s+/g, ' ').trim();
    if (desc.length > DESC_MAX) desc = desc.slice(0, DESC_MAX - 1).trimEnd() + '…';

    (tx[id] = tx[id] || []).push([hz, mode, r.baud || 0, desc, r.service || '']);
    kept++;
  }

  let objects = 0, records = 0;
  for (const id of Object.keys(tx)) {
    const seen = new Set();
    const list = tx[id]
      .filter(t => { const k = t[0] + '|' + t[1]; if (seen.has(k)) return false; seen.add(k); return true; })
      .sort((a, b) => a[0] - b[0])
      .slice(0, MAX_TX);
    tx[id] = list;
    objects++; records += list.length;
  }

  console.log('\nkept              : ' + records + ' transmitters on ' + objects + ' objects');
  console.log('  not in catalogue: ' + skippedNotOurs);
  console.log('  not active      : ' + skippedDead);
  console.log('  no downlink     : ' + skippedNoDown);
  console.log('  deduped/capped  : ' + (kept - records));
  console.log('  coverage        : ' + (100 * objects / ids.size).toFixed(1) + '% of the catalogue');

  const bands = { 'VHF 144-148': 0, 'UHF 420-450': 0, 'S 2.2-2.3': 0, 'other': 0 };
  for (const id of Object.keys(tx)) for (const t of tx[id]) {
    const m = t[0] / 1e6;
    if (m >= 144 && m <= 148) bands['VHF 144-148']++;
    else if (m >= 420 && m <= 450) bands['UHF 420-450']++;
    else if (m >= 2200 && m <= 2300) bands['S 2.2-2.3']++;
    else bands.other++;
  }
  console.log('  bands (MHz)     : ' + JSON.stringify(bands));

  const body = Object.keys(tx).sort((a, b) => a - b)
    .map(id => '  ' + id + ':' + JSON.stringify(tx[id])).join(',\n');

  const out = `/* Downlink frequencies, baked from SatNOGS DB. Generated by
   verification/fetch-transmitters.js - do not edit by hand.

   Active transmitters with a published downlink, deduplicated on frequency and
   mode, at most ${MAX_TX} per object, lowest first. Objects absent from this file
   have no active downlink in SatNOGS, which is the common case for the
   government and commercial half of the catalogue: the page says so rather than
   guessing a frequency.

   Each record is [downlinkHz, mode, baud, description, service]. */
window.Transmitters = (function(){
  const BUILT = ${JSON.stringify(new Date().toISOString())};
  const SOURCE = 'SatNOGS DB — db.satnogs.org/api/transmitters/';
  const TX = {
${body}
  };
  return {
    built: BUILT, source: SOURCE,
    objects: ${objects}, records: ${records},
    /* Every active downlink for a NORAD id, or an empty array. Never null: a
       caller that forgets to check should render nothing, not crash. */
    forSat(satnum){
      const l = TX[satnum];
      return l ? l.map(t => ({ hz: t[0], mode: t[1], baud: t[2], desc: t[3], service: t[4] })) : [];
    },
    /* The one to tune first: lowest frequency among the active downlinks. */
    primary(satnum){
      const l = this.forSat(satnum);
      return l.length ? l[0] : null;
    },
    has(satnum){ return !!TX[satnum]; }
  };
})();
`;
  fs.writeFileSync(OUT, out);
  console.log('\nwritten: ' + OUT + '  (' + (out.length / 1024).toFixed(0) + ' KB)');
})();
